def test_build_on_template(tmp_path):
    tpl = tmp_path / "t.RPP"
    tpl.write_text(TEMPLATE)
    chart = Chart(TempoMap.click_tracked(140, 2.0))
    chart.track("PART DRUMS").add_note(1920, 60, 96)
    chart.track("PART VOCALS").add_lyric(1920, "hey").add_note(1920, 120, 60)
    root = rproject.build(chart, {}, [ReviewItem(4.25, "vocals", "check me")], tpl)

    tracks = list(root.nodes("TRACK"))
    assert [t.value("NAME")[0] for t in tracks] == ["PART DRUMS", "PART VOCALS"]
    # template track kept its FX and settings, got a fresh MIDI item
    drums = tracks[0]
    assert drums.find("FXCHAIN") is not None and drums.line("VOLPAN") is not None
    items = list(drums.nodes("ITEM"))
    assert len(items) == 1 and items[0].find("SOURCE").args == ["MIDI"]
    # lyric written as a base64 meta event
    assert any(n.name == "X" for n in tracks[1].find("ITEM").find("SOURCE").nodes())
    # tempo envelope: offset measure + locked tempo
    pts = [ln.tokens for ln in root.find("TEMPOENVEX").children if ln.key == "PT"]
    assert len(pts) == 2 and abs(float(pts[1][2]) - 140) < 1e-3  # MIDI tempo is whole microseconds
    # user's marker kept, review marker added with the next free index
    markers = [ln.tokens for ln in root.children if getattr(ln, "key", None) == "MARKER"]
    assert markers[0][3] == "Mine" and markers[1][1] == "2" and "check me" in markers[1][3]
    # re-parse what we wrote
    parse(dumps(root))
